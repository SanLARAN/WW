function colorFor(id: string): string {
  const h = hashString(id);
  const hue = h % 360, sat = 28 + ((h >> 9) % 30), light = 38 + ((h >> 17) % 22);
  return hslToHex(hue, sat / 100, light / 100);
}

function hslToHex(h: number, s: number, l: number): string {
  const k = (n: number) => (n + h / 30) % 12;
  const a = s * Math.min(l, 1 - l);
  const f = (n: number) => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
  const hex = (x: number) => Math.round(x * 255).toString(16).padStart(2, '0');
  return `#${hex(f(0))}${hex(f(8))}${hex(f(4))}`;
}

function minorDef(id: string, gdp: number, pop: number): CountryDef {
  const perCap = (gdp * 1000) / Math.max(0.01, pop); // $ thousands per person
  const tech = Math.max(1, Math.min(8, Math.round(Math.log2(perCap + 1) * 1.3)));
  const forces = Math.max(1, Math.round(Math.log10(gdp + 1) * 1.6));
  return {
    id, name: NAMES[id] ?? id, tier: gdp > 300 ? 'C' : 'D', color: colorFor(id), gdp, pop, mil: +(gdp * 0.018).toFixed(2), tech, nukes: 0,
    res: [1, 1, 0, 1, 0, 3],
    army: [forces, Math.floor(forces / 2), Math.floor(forces / 2), Math.floor(forces / 3), 0, Math.floor(forces / 3), 0, 0],
    alliances: MINOR_ALLIANCES[id] ?? [], corruption: perCap > 25 ? 20 : perCap > 8 ? 45 : 70, stability: perCap > 25 ? 75 : 50,
    ideology: [0, 30, 20, perCap > 25 ? -70 : 20], econ: 'mixed', aggression: 0.1, detailed: false,
  };
}

let cache: Map<string, CountryDef> | null = null;

export function countryDefs(): Map<string, CountryDef> {
  if (cache) return cache;
  const m = parseDetailed();
  for (const tok of MINOR.split(/\s+/).filter(Boolean)) {
    const [id, gdp, pop] = tok.split(':');
    if (!m.has(id)) m.set(id, minorDef(id, +gdp, +pop));
  }
  for (const id of Object.keys(NAMES)) if (!m.has(id)) m.set(id, minorDef(id, 1, 0.05));
  cache = m;
  return m;
}
